PRAGMA foreign_keys = OFF;
DROP TABLE IF EXISTS TB_RELATORIOS_ANUAIS;
DROP TABLE IF EXISTS TB_OBSERVACOES;
DROP TABLE IF EXISTS TB_CHAMADA;
DROP TABLE IF EXISTS TB_FERIADOS;
DROP TABLE IF EXISTS TB_ALUNOS;
DROP TABLE IF EXISTS TB_TURMAS;
DROP TABLE IF EXISTS TB_PERIODOS;
DROP TABLE IF EXISTS TB_ACESSO;
DROP TABLE IF EXISTS TB_USUARIOS;
DROP TABLE IF EXISTS TB_UNIDADES;

CREATE TABLE TB_UNIDADES (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  unidade TEXT NOT NULL,
  data_cadastro TEXT DEFAULT (datetime('now','localtime'))
);

CREATE TABLE TB_USUARIOS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  NOME TEXT, SENHA TEXT, NIVEL INTEGER, CPF TEXT,
  CREATED TEXT, MODIFIED TEXT, ATIVO INTEGER, USUARIO INTEGER
);

CREATE TABLE TB_ACESSO (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  id_usuario INTEGER NOT NULL REFERENCES TB_USUARIOS(ID),
  id_unidade INTEGER NOT NULL REFERENCES TB_UNIDADES(id),
  ativo INTEGER DEFAULT 1,
  data_cadastro TEXT DEFAULT (datetime('now','localtime')),
  desativado TEXT
);

CREATE TABLE TB_PERIODOS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  NOME TEXT NOT NULL UNIQUE,
  HORA_INICIO TEXT NOT NULL,
  HORA_FIM TEXT NOT NULL,
  ATIVO INTEGER NOT NULL DEFAULT 1,
  CREATED TEXT NOT NULL DEFAULT (datetime('now','localtime')),
  CHECK (HORA_FIM > HORA_INICIO)
);

CREATE TABLE TB_TURMAS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  ID_UNIDADE INTEGER NOT NULL REFERENCES TB_UNIDADES(id),
  NOME TEXT NOT NULL,
  ANO_LETIVO INTEGER NOT NULL CHECK (ANO_LETIVO BETWEEN 2000 AND 2100),
  ID_PERIODO INTEGER NOT NULL REFERENCES TB_PERIODOS(ID),
  ID_PROFESSOR INTEGER REFERENCES TB_USUARIOS(ID),
  CAPACIDADE INTEGER NOT NULL DEFAULT 20 CHECK (CAPACIDADE BETWEEN 1 AND 500),
  ATIVO INTEGER NOT NULL DEFAULT 1,
  CREATED TEXT NOT NULL DEFAULT (datetime('now','localtime')),
  UNIQUE (ID_UNIDADE, NOME, ANO_LETIVO)
);

CREATE TABLE TB_ALUNOS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  ID_TURMA INTEGER NOT NULL REFERENCES TB_TURMAS(ID),
  MATRICULA TEXT NOT NULL UNIQUE,
  NOME TEXT NOT NULL,
  NASCIMENTO TEXT NOT NULL,
  DATA_MATRICULA TEXT NOT NULL,
  RESPONSAVEL TEXT NOT NULL,
  TELEFONE TEXT NOT NULL,
  EMAIL TEXT,
  ATIVO INTEGER NOT NULL DEFAULT 1,
  CREATED TEXT NOT NULL DEFAULT (datetime('now','localtime'))
);

CREATE TABLE TB_FERIADOS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  DATA TEXT NOT NULL,
  DESCRICAO TEXT NOT NULL,
  TIPO TEXT NOT NULL CHECK (TIPO IN ('INTEGRAL','PARCIAL')),
  HORA_INICIO TEXT, HORA_FIM TEXT,
  ID_UNIDADE INTEGER REFERENCES TB_UNIDADES(id),
  CREATED TEXT NOT NULL DEFAULT (datetime('now','localtime'))
);

CREATE TABLE TB_CHAMADA (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  ID_ALUNO INTEGER NOT NULL REFERENCES TB_ALUNOS(ID),
  DATA TEXT NOT NULL,
  STATUS TEXT NOT NULL CHECK (STATUS IN ('P','F','J','A')),
  JUSTIFICATIVA TEXT,
  ID_USUARIO INTEGER NOT NULL REFERENCES TB_USUARIOS(ID),
  CREATED TEXT NOT NULL DEFAULT (datetime('now','localtime')),
  MODIFIED TEXT,
  UNIQUE (ID_ALUNO, DATA)
);

CREATE TABLE TB_OBSERVACOES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  ID_ALUNO INTEGER NOT NULL REFERENCES TB_ALUNOS(ID),
  DATA TEXT NOT NULL,
  CATEGORIA TEXT NOT NULL,
  TEXTO TEXT NOT NULL,
  ID_USUARIO INTEGER NOT NULL REFERENCES TB_USUARIOS(ID),
  CREATED TEXT NOT NULL DEFAULT (datetime('now','localtime')),
  MODIFIED TEXT
);

CREATE TABLE TB_RELATORIOS_ANUAIS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  ID_ALUNO INTEGER NOT NULL REFERENCES TB_ALUNOS(ID),
  ANO INTEGER NOT NULL,
  PARECER TEXT, ENCAMINHAMENTOS TEXT,
  ID_USUARIO INTEGER NOT NULL REFERENCES TB_USUARIOS(ID),
  CREATED TEXT NOT NULL DEFAULT (datetime('now','localtime')),
  MODIFIED TEXT,
  UNIQUE (ID_ALUNO, ANO)
);

CREATE INDEX IX_CHAMADA_DATA ON TB_CHAMADA(DATA);
CREATE INDEX IX_OBS_ALUNO ON TB_OBSERVACOES(ID_ALUNO, DATA);
CREATE INDEX IX_ALUNOS_TURMA ON TB_ALUNOS(ID_TURMA, ATIVO);

