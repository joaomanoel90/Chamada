/* Suspensão de alunos por período — atualização idempotente.
   SQL Server 2016 ou mais novo. Executar no banco db_chamada.

   Registra suspensões com início, fim, motivo e quem determinou. As faltas
   geradas em TB_CHAMADA ficam ligadas à suspensão por ID_SUSPENSAO.

   Cada liberação parcial grava quais datas/aulas foram tiradas, se houve
   lançamento de presença nos dias já passados, o motivo e o usuário. Quando
   todas as faltas ligadas são liberadas, a suspensão passa a ENCERRADA.

   Pode ser executado mais de uma vez sem apagar histórico. */
USE [db_chamada];
GO

PRINT '';
PRINT 'Suspensão de alunos por período';
GO

IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_SUSPENSOES_ALUNOS (
        ID                      int IDENTITY(1,1) NOT NULL,
        ID_ALUNO                int           NOT NULL,
        DATA_INICIO             date          NOT NULL,
        DATA_FIM                date          NOT NULL,
        MOTIVO                  nvarchar(500) NOT NULL,
        ID_USUARIO              int           NOT NULL,
        CRIADO_EM               datetime2(0)  NOT NULL
            CONSTRAINT DF_SUSP_ALUNO_CRIADO DEFAULT (SYSDATETIME()),
        SITUACAO                varchar(10)   NOT NULL
            CONSTRAINT DF_SUSP_ALUNO_SITUACAO DEFAULT ('ATIVA'),
        ENCERRADA_EM            datetime2(0)  NULL,
        ID_USUARIO_ENCERRAMENTO int           NULL,
        MOTIVO_ENCERRAMENTO     nvarchar(500) NULL,
        CONSTRAINT PK_TB_SUSP_ALUNOS PRIMARY KEY CLUSTERED (ID),
        CONSTRAINT FK_SUSP_ALUNO_ALUNO FOREIGN KEY (ID_ALUNO)
            REFERENCES dbo.TB_ALUNOS (ID),
        CONSTRAINT FK_SUSP_ALUNO_USUARIO FOREIGN KEY (ID_USUARIO)
            REFERENCES dbo.TB_USUARIOS (ID),
        CONSTRAINT FK_SUSP_ALUNO_USUARIO_FIM FOREIGN KEY (ID_USUARIO_ENCERRAMENTO)
            REFERENCES dbo.TB_USUARIOS (ID),
        CONSTRAINT CK_SUSP_ALUNO_PERIODO CHECK (DATA_FIM >= DATA_INICIO),
        CONSTRAINT CK_SUSP_ALUNO_MOTIVO CHECK (LTRIM(RTRIM(MOTIVO)) <> N''),
        CONSTRAINT CK_SUSP_ALUNO_MOTIVO_FIM CHECK (
            MOTIVO_ENCERRAMENTO IS NULL OR LTRIM(RTRIM(MOTIVO_ENCERRAMENTO)) <> N''),
        CONSTRAINT CK_SUSP_ALUNO_SITUACAO CHECK (SITUACAO IN ('ATIVA', 'ENCERRADA')),
        CONSTRAINT CK_SUSP_ALUNO_ENCERRAMENTO CHECK (
            (SITUACAO = 'ATIVA'
             AND ENCERRADA_EM IS NULL
             AND ID_USUARIO_ENCERRAMENTO IS NULL
             AND MOTIVO_ENCERRAMENTO IS NULL)
            OR
            (SITUACAO = 'ENCERRADA'
             AND ENCERRADA_EM IS NOT NULL
             AND ID_USUARIO_ENCERRAMENTO IS NOT NULL
             AND MOTIVO_ENCERRAMENTO IS NOT NULL)
        )
    );
    CREATE INDEX IX_SUSP_ALUNO_PERIODO
        ON dbo.TB_SUSPENSOES_ALUNOS (ID_ALUNO, DATA_INICIO DESC, DATA_FIM DESC);
    PRINT '  + TB_SUSPENSOES_ALUNOS criada';
END
ELSE
    PRINT '  = TB_SUSPENSOES_ALUNOS já existe';
GO

/* Histórico de dias/aulas liberados antes do fim da suspensão. */
IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES (
        ID               int IDENTITY(1,1) NOT NULL,
        ID_SUSPENSAO     int           NOT NULL,
        DATA_LIBERADA    date          NOT NULL,
        AULA_SEQ         int           NOT NULL,
        PRESENCA_LANCADA bit           NOT NULL
            CONSTRAINT DF_SUSP_LIB_PRESENCA DEFAULT (0),
        MOTIVO           nvarchar(500) NOT NULL,
        ID_USUARIO       int           NOT NULL,
        CRIADO_EM        datetime2(0)  NOT NULL
            CONSTRAINT DF_SUSP_LIB_CRIADO DEFAULT (SYSDATETIME()),
        CONSTRAINT PK_TB_SUSP_LIB PRIMARY KEY CLUSTERED (ID),
        CONSTRAINT FK_SUSP_LIB_SUSP FOREIGN KEY (ID_SUSPENSAO)
            REFERENCES dbo.TB_SUSPENSOES_ALUNOS (ID),
        CONSTRAINT FK_SUSP_LIB_USUARIO FOREIGN KEY (ID_USUARIO)
            REFERENCES dbo.TB_USUARIOS (ID),
        CONSTRAINT UQ_SUSP_LIB_DIA_AULA UNIQUE (ID_SUSPENSAO, DATA_LIBERADA, AULA_SEQ),
        CONSTRAINT CK_SUSP_LIB_AULA CHECK (AULA_SEQ IN (1, 2)),
        CONSTRAINT CK_SUSP_LIB_MOTIVO CHECK (LTRIM(RTRIM(MOTIVO)) <> N'')
    );
    CREATE INDEX IX_SUSP_LIB_SUSP_DIA
        ON dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES (ID_SUSPENSAO, DATA_LIBERADA);
    PRINT '  + TB_SUSPENSOES_ALUNOS_LIBERACOES criada';
END
ELSE
    PRINT '  = TB_SUSPENSOES_ALUNOS_LIBERACOES já existe';
GO

IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES', N'U') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.check_constraints
        WHERE name = N'CK_SUSP_LIB_AULA'
          AND parent_object_id = OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES')
   )
BEGIN
    ALTER TABLE dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES WITH CHECK
        ADD CONSTRAINT CK_SUSP_LIB_AULA CHECK (AULA_SEQ IN (1, 2));
    PRINT '  + CK_SUSP_LIB_AULA criada';
END
GO

IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES', N'U') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.check_constraints
        WHERE name = N'CK_SUSP_LIB_MOTIVO'
          AND parent_object_id = OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES')
   )
BEGIN
    ALTER TABLE dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES WITH CHECK
        ADD CONSTRAINT CK_SUSP_LIB_MOTIVO CHECK (LTRIM(RTRIM(MOTIVO)) <> N'');
    PRINT '  + CK_SUSP_LIB_MOTIVO criada';
END
GO

IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES', N'U') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.indexes
        WHERE name = N'IX_SUSP_LIB_SUSP_DIA'
          AND object_id = OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES')
   )
BEGIN
    CREATE INDEX IX_SUSP_LIB_SUSP_DIA
        ON dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES (ID_SUSPENSAO, DATA_LIBERADA);
    PRINT '  + IX_SUSP_LIB_SUSP_DIA criado';
END
GO

IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES', N'U') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.indexes
        WHERE name = N'UQ_SUSP_LIB_DIA_AULA'
          AND object_id = OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES')
   )
BEGIN
    ALTER TABLE dbo.TB_SUSPENSOES_ALUNOS_LIBERACOES
        ADD CONSTRAINT UQ_SUSP_LIB_DIA_AULA UNIQUE (ID_SUSPENSAO, DATA_LIBERADA, AULA_SEQ);
    PRINT '  + UQ_SUSP_LIB_DIA_AULA criada';
END
GO

/* Bases parcialmente atualizadas recebem o que estiver faltando. */
IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS', N'U') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.check_constraints
        WHERE name = N'CK_SUSP_ALUNO_PERIODO'
          AND parent_object_id = OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS')
   )
BEGIN
    ALTER TABLE dbo.TB_SUSPENSOES_ALUNOS
        ADD CONSTRAINT CK_SUSP_ALUNO_PERIODO CHECK (DATA_FIM >= DATA_INICIO);
    PRINT '  + CK_SUSP_ALUNO_PERIODO criada';
END
GO

IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS', N'U') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.check_constraints
        WHERE name = N'CK_SUSP_ALUNO_MOTIVO'
          AND parent_object_id = OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS')
   )
BEGIN
    ALTER TABLE dbo.TB_SUSPENSOES_ALUNOS WITH CHECK
        ADD CONSTRAINT CK_SUSP_ALUNO_MOTIVO CHECK (LTRIM(RTRIM(MOTIVO)) <> N'');
    PRINT '  + CK_SUSP_ALUNO_MOTIVO criada';
END
GO

IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS', N'U') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.check_constraints
        WHERE name = N'CK_SUSP_ALUNO_MOTIVO_FIM'
          AND parent_object_id = OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS')
   )
BEGIN
    ALTER TABLE dbo.TB_SUSPENSOES_ALUNOS WITH CHECK
        ADD CONSTRAINT CK_SUSP_ALUNO_MOTIVO_FIM CHECK (
            MOTIVO_ENCERRAMENTO IS NULL OR LTRIM(RTRIM(MOTIVO_ENCERRAMENTO)) <> N'');
    PRINT '  + CK_SUSP_ALUNO_MOTIVO_FIM criada';
END
GO

IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS', N'U') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.check_constraints
        WHERE name = N'CK_SUSP_ALUNO_SITUACAO'
          AND parent_object_id = OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS')
   )
BEGIN
    ALTER TABLE dbo.TB_SUSPENSOES_ALUNOS
        ADD CONSTRAINT CK_SUSP_ALUNO_SITUACAO CHECK (SITUACAO IN ('ATIVA', 'ENCERRADA'));
    PRINT '  + CK_SUSP_ALUNO_SITUACAO criada';
END
GO

IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS', N'U') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.check_constraints
        WHERE name = N'CK_SUSP_ALUNO_ENCERRAMENTO'
          AND parent_object_id = OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS')
   )
BEGIN
    ALTER TABLE dbo.TB_SUSPENSOES_ALUNOS
        ADD CONSTRAINT CK_SUSP_ALUNO_ENCERRAMENTO CHECK (
            (SITUACAO = 'ATIVA'
             AND ENCERRADA_EM IS NULL
             AND ID_USUARIO_ENCERRAMENTO IS NULL
             AND MOTIVO_ENCERRAMENTO IS NULL)
            OR
            (SITUACAO = 'ENCERRADA'
             AND ENCERRADA_EM IS NOT NULL
             AND ID_USUARIO_ENCERRAMENTO IS NOT NULL
             AND MOTIVO_ENCERRAMENTO IS NOT NULL)
        );
    PRINT '  + CK_SUSP_ALUNO_ENCERRAMENTO criada';
END
GO

IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS', N'U') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.foreign_keys
        WHERE name = N'FK_SUSP_ALUNO_USUARIO_FIM'
          AND parent_object_id = OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS')
   )
BEGIN
    ALTER TABLE dbo.TB_SUSPENSOES_ALUNOS WITH CHECK
        ADD CONSTRAINT FK_SUSP_ALUNO_USUARIO_FIM FOREIGN KEY (ID_USUARIO_ENCERRAMENTO)
            REFERENCES dbo.TB_USUARIOS (ID);
    PRINT '  + FK_SUSP_ALUNO_USUARIO_FIM criada';
END
GO

IF OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS', N'U') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.indexes
        WHERE name = N'IX_SUSP_ALUNO_PERIODO'
          AND object_id = OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS')
   )
BEGIN
    CREATE INDEX IX_SUSP_ALUNO_PERIODO
        ON dbo.TB_SUSPENSOES_ALUNOS (ID_ALUNO, DATA_INICIO DESC, DATA_FIM DESC);
    PRINT '  + IX_SUSP_ALUNO_PERIODO criado';
END
GO

/* Liga cada falta gerada à suspensão que a originou. */
IF OBJECT_ID(N'dbo.TB_CHAMADA', N'U') IS NOT NULL
   AND COL_LENGTH(N'dbo.TB_CHAMADA', N'ID_SUSPENSAO') IS NULL
BEGIN
    ALTER TABLE dbo.TB_CHAMADA ADD ID_SUSPENSAO int NULL;
    PRINT '  + TB_CHAMADA.ID_SUSPENSAO adicionada';
END
GO

IF OBJECT_ID(N'dbo.TB_CHAMADA', N'U') IS NOT NULL
   AND OBJECT_ID(N'dbo.TB_SUSPENSOES_ALUNOS', N'U') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.foreign_keys
        WHERE name = N'FK_CHAMADA_SUSPENSAO'
          AND parent_object_id = OBJECT_ID(N'dbo.TB_CHAMADA')
   )
BEGIN
    ALTER TABLE dbo.TB_CHAMADA WITH CHECK
        ADD CONSTRAINT FK_CHAMADA_SUSPENSAO FOREIGN KEY (ID_SUSPENSAO)
            REFERENCES dbo.TB_SUSPENSOES_ALUNOS (ID);
    PRINT '  + FK_CHAMADA_SUSPENSAO criada';
END
GO

IF OBJECT_ID(N'dbo.TB_CHAMADA', N'U') IS NOT NULL
   AND COL_LENGTH(N'dbo.TB_CHAMADA', N'ID_SUSPENSAO') IS NOT NULL
   AND NOT EXISTS (
       SELECT 1 FROM sys.indexes
        WHERE name = N'IX_CHAMADA_SUSPENSAO'
          AND object_id = OBJECT_ID(N'dbo.TB_CHAMADA')
   )
BEGIN
    CREATE INDEX IX_CHAMADA_SUSPENSAO
        ON dbo.TB_CHAMADA (ID_SUSPENSAO)
        WHERE ID_SUSPENSAO IS NOT NULL;
    PRINT '  + IX_CHAMADA_SUSPENSAO criado';
END
GO

PRINT 'Atualização de suspensão de alunos concluída.';
GO
